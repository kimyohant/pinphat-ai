/** ชื่อโมเดลที่แสดงบนจอ ประกอบจากค่าตั้งของการรันตามภาษาของผู้อ่าน */
export function runName(c: RunConfig, ui: EvalUi): string {
  if (c.provider === "baseline") return ui.baseline;
  const name = c.model.replace(/^unsloth\//, "");
  if (c.provider === "claude") return `${name} (Claude)`;
  return `${name}${c.variant ? ` · ${c.variant}` : ""} · ${c.thinking ? ui.modeThink : ui.modeFast}`;
}
